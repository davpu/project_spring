/**
 * Turns the Zod telemetry contract into artifacts for the parts of the system
 * that cannot import TypeScript:
 *
 *   - a JSON Schema the gateway (Node-RED) validates against
 *   - a C++ header the ESP32 firmware includes
 *
 * This module only builds strings. Writing them is
 * `libs/shared/scripts/generate-contract.mts`; `codegen.spec.ts` asserts the
 * committed files still match, so a change here fails CI until the artifacts
 * are regenerated and committed.
 */
import { z } from 'zod';

import { METRICS, METRIC_UNITS, TelemetryPayloadSchema } from './metrics.js';
import {
  NODE_TELEMETRY_TOPIC,
  SensorKeySchema,
  nodeTopics,
  topics,
} from './topics.js';

export const GENERATOR = 'libs/shared/scripts/generate-contract.mts';
export const SOURCE_OF_TRUTH = 'libs/shared/src/lib/metrics.ts';

/** Paths are relative to the repo root. */
export const ARTIFACTS = {
  jsonSchema: 'infra/nodered/contract/telemetry.schema.json',
  gatewayMeta: 'infra/nodered/contract/contract.json',
  firmwareHeader: 'firmware/include/contract.h',
} as const;

/**
 * Node-RED 4.0 builds the core `json` node's validator as `new Ajv()` on ajv 8,
 * which means draft-07. Zod's default draft 2020-12 would not compile there.
 */
const JSON_SCHEMA_TARGET = 'draft-7' as const;

const AUTO_GENERATED = `AUTO-GENERATED by ${GENERATOR} - do not edit by hand.`;

/**
 * Drops every `format` keyword. Node-RED's ajv has no ajv-formats plugin, and
 * an unknown format makes it refuse to compile the whole schema rather than
 * skip the keyword. Zod emits an equivalent `pattern` next to each `format`, so
 * validation is unaffected.
 */
function stripFormat(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(stripFormat);
  if (node === null || typeof node !== 'object') return node;
  return Object.fromEntries(
    Object.entries(node)
      .filter(([key]) => key !== 'format')
      .map(([key, value]) => [key, stripFormat(value)]),
  );
}

const NumericFieldSchema = z.object({
  type: z.enum(['number', 'integer']),
  minimum: z.number().optional(),
  maximum: z.number().optional(),
  multipleOf: z.number().optional(),
});
type NumericField = z.infer<typeof NumericFieldSchema>;

const GeneratableSchema = z.object({
  $schema: z.literal('http://json-schema.org/draft-07/schema#'),
  type: z.literal('object'),
  properties: z.record(z.string(), z.unknown()),
  additionalProperties: z.literal(false),
});

/**
 * Validates the shape the generators rely on and returns the schema unchanged.
 * Parsing for the return value would silently drop every keyword not listed
 * above, `$schema` included.
 */
function assertGeneratable(generated: unknown): Record<string, unknown> {
  return {
    ...GeneratableSchema.parse(generated),
    ...(generated as Record<string, unknown>),
  };
}

function payloadJsonSchema(): Record<string, unknown> {
  return assertGeneratable(
    stripFormat(
      z.toJSONSchema(TelemetryPayloadSchema, { target: JSON_SCHEMA_TARGET }),
    ),
  );
}

/** The JSON Schema the gateway validates telemetry against. */
export function buildTelemetryJsonSchema(): Record<string, unknown> {
  // `.refine()` has no JSON Schema equivalent and Zod drops it silently, so the
  // "at least one measurement" rule has to be restated here. Without it the
  // gateway would forward an empty object that the API then rejects.
  return {
    $comment: AUTO_GENERATED,
    ...payloadJsonSchema(),
    anyOf: METRICS.map((metric) => ({ required: [metric] })),
  };
}

/** Topic shapes and formats the gateway flow needs but cannot import. */
export function buildGatewayMeta(): Record<string, unknown> {
  return {
    $comment: AUTO_GENERATED,
    sensorKeyPattern: sensorKeyPattern(),
    node: {
      telemetryFilter: nodeTopics.telemetryFilter,
      topicPrefix: NODE_TELEMETRY_TOPIC.prefix,
      topicSuffix: NODE_TELEMETRY_TOPIC.suffix,
    },
    cloud: {
      /** Substitute `{gatewayId}` and `{sensorKey}`. */
      telemetryTopic: topics.telemetry('{gatewayId}', '{sensorKey}'),
      statusTopic: topics.status('{gatewayId}'),
    },
  };
}

function sensorKeyPattern(): string {
  const schema = z.toJSONSchema(SensorKeySchema, {
    target: JSON_SCHEMA_TARGET,
  });
  return z.object({ pattern: z.string() }).parse(schema).pattern;
}

function metricField(
  properties: Record<string, unknown>,
  metric: string,
): NumericField {
  const field = properties[metric];
  if (field === undefined) {
    throw new Error(`metric "${metric}" is missing from the payload schema`);
  }
  return NumericFieldSchema.parse(field);
}

const CPP_TYPES: Record<NumericField['type'], string> = {
  number: 'float',
  integer: 'int',
};

/** `airTemperature` -> `AIR_TEMPERATURE` */
function constantName(field: string): string {
  return field.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
}

function cppLiteral(value: number, type: NumericField['type']): string {
  if (type === 'integer') {
    if (!Number.isInteger(value)) {
      throw new Error(`bound ${value} is not an integer`);
    }
    return String(value);
  }
  return `${Number.isInteger(value) ? value.toFixed(1) : String(value)}f`;
}

/** The C++ header the ESP32 firmware includes. */
export function buildFirmwareHeader(): string {
  const properties = z
    .record(z.string(), z.unknown())
    .parse(payloadJsonSchema()['properties']);
  const fields = METRICS.map((metric) => ({
    metric,
    field: metricField(properties, metric),
  }));

  const constants = fields.flatMap(({ metric, field }) => {
    const name = constantName(metric);
    const cppType = CPP_TYPES[field.type];
    const lines = [`// ${metric} in ${METRIC_UNITS[metric]}`];
    if (field.minimum !== undefined) {
      lines.push(
        `inline constexpr ${cppType} ${name}_MIN = ${cppLiteral(field.minimum, field.type)};`,
      );
    }
    if (field.maximum !== undefined) {
      lines.push(
        `inline constexpr ${cppType} ${name}_MAX = ${cppLiteral(field.maximum, field.type)};`,
      );
    }
    if (field.multipleOf !== undefined) {
      lines.push(
        `inline constexpr float ${name}_RESOLUTION = ${cppLiteral(field.multipleOf, 'number')};`,
      );
    }
    if (lines.length === 1) lines.push(`// no bounds in the contract`);
    lines.push('');
    return lines;
  });

  const members = fields.map(
    ({ metric, field }) => `  ${CPP_TYPES[field.type]} ${metric};`,
  );

  const assignments = fields.map(({ metric, field }) =>
    field.multipleOf === undefined
      ? `  doc["${metric}"] = reading.${metric};`
      : `  doc["${metric}"] = roundToResolution(reading.${metric}, ${constantName(metric)}_RESOLUTION);`,
  );

  return [
    `// ${AUTO_GENERATED}`,
    `// Source of truth: ${SOURCE_OF_TRUTH}`,
    '// Regenerate with: pnpm contract:gen',
    '',
    '#pragma once',
    '',
    '#include <ArduinoJson.h>',
    '#include <math.h>',
    '#include <stddef.h>',
    '#include <stdio.h>',
    '',
    'namespace contract {',
    '',
    '// A node publishes to the local broker under its own sensor key; the',
    '// gateway revalidates the payload and republishes it upstream unchanged.',
    `inline constexpr char TELEMETRY_TOPIC_PREFIX[] = ${JSON.stringify(NODE_TELEMETRY_TOPIC.prefix)};`,
    `inline constexpr char TELEMETRY_TOPIC_SUFFIX[] = ${JSON.stringify(NODE_TELEMETRY_TOPIC.suffix)};`,
    `inline constexpr char SENSOR_KEY_PATTERN[] = ${JSON.stringify(sensorKeyPattern())};`,
    '',
    '// Writes "<prefix>/<sensorKey>/<suffix>". Returns the number of bytes the',
    '// topic needs, so a result >= len means the buffer was too small.',
    'inline int telemetryTopic(const char* sensorKey, char* out, size_t len) {',
    '  return snprintf(out, len, "%s/%s/%s", TELEMETRY_TOPIC_PREFIX, sensorKey,',
    '                  TELEMETRY_TOPIC_SUFFIX);',
    '}',
    '',
    ...constants,
    'struct TelemetryPayload {',
    ...members,
    '};',
    '',
    '// Clamps a value to the resolution the contract allows, so a node cannot',
    '// claim more precision than its sensor delivers.',
    'inline float roundToResolution(float value, float resolution) {',
    '  return resolution <= 0.0f ? value : roundf(value / resolution) * resolution;',
    '}',
    '',
    '// Serializes a reading to the telemetry JSON body. Returns the number of',
    '// bytes written, excluding the terminating null; if the output does not fit',
    '// it is truncated, so check the result is below len - 1.',
    'inline size_t serialize(const TelemetryPayload& reading, char* out,',
    '                        size_t len) {',
    '  JsonDocument doc;',
    ...assignments,
    '  return serializeJson(doc, out, len);',
    '}',
    '',
    '}  // namespace contract',
    '',
  ].join('\n');
}

/** Serializes a JSON artifact the way Prettier would. */
export function formatJson(value: Record<string, unknown>): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}
